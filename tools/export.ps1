# Writes this repo's config files from the current user profile, with the work root replaced by placeholders.
# Only whitelisted settings are exported (no auth files, no app-managed Codex keys). The result is checked before it is left in place.
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\export.ps1 -Root <work root>
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\export.ps1 -CheckOnly
param([string]$Root, [string]$ProfileDir=$env:USERPROFILE, [switch]$CheckOnly)
$ErrorActionPreference='Stop'
$repo=Split-Path -Parent $PSScriptRoot
$files='claude/settings.json','claude/CLAUDE.md','codex/AGENTS.md','codex/config.toml'

function Test-ConfigFiles([string]$Dir) {
    # Same rules the installer applies to a downloaded copy: every file present, settings.json parses, config.toml has only
    # [section] / key = value / comment lines, only the two known placeholders, and nothing that identifies this PC or account.
    $err=@()
    foreach ($f in $files) {
        $p=Join-Path $Dir $f
        if (-not (Test-Path $p)) { $err+="missing $f"; continue }
        $t=[IO.File]::ReadAllText($p, [Text.Encoding]::UTF8)
        if ($t -match '(?<![A-Za-z])[A-Za-z]:[\\/]') { $err+="absolute path in ${f}: $($matches[0])" }
        if ($t -match '[\w.+-]+@[\w-]+(\.[\w-]+)+') { $err+="e-mail address in $f" }
        if ($t -match '(?i)j73coy|\\Users\\') { $err+="account name in $f" }
        if ($t -match '\{\{(?!WORK_ROOT(_SLASH)?\}\})') { $err+="unknown placeholder in $f" }
        if ($f -like '*.json') { try { $null=$t | ConvertFrom-Json } catch { $err+="settings.json does not parse: $($_.Exception.Message)" } }
        if ($f -like '*.toml') {
            foreach ($line in ($t -split "`r?`n")) {
                if ($line -notmatch '^\s*$|^\s*#|^\s*\[[^\]]+\]\s*$|^\s*[A-Za-z0-9_."''-]+\s*=\s*\S') { $err+="config.toml line not understood: $line" }
            }
        }
    }
    return $err
}

if (-not $CheckOnly) {
    if (-not $Root) { throw '-Root is required (the work root of this PC)' }
    $Root=$Root.TrimEnd('\')
    $out=@{}
    $read={ param($p) [IO.File]::ReadAllText((Join-Path $ProfileDir $p), [Text.Encoding]::UTF8) }
    $hide={ param($t) $t.Replace($Root.Replace('\','/'), '{{WORK_ROOT_SLASH}}').Replace($Root, '{{WORK_ROOT}}') }
    $out['claude/settings.json']=& $hide (& $read '.claude\settings.json')
    $out['claude/CLAUDE.md']=& $hide (& $read '.claude\CLAUDE.md')
    $out['codex/AGENTS.md']=& $hide (& $read '.codex\AGENTS.md')
    # config.toml: the user's keys only. notify, marketplaces, plugins, mcp_servers and windows hold app runtime paths and are
    # regenerated by the app; per-repo trust entries are added by the app when a folder is first opened.
    $keepTop='model','model_reasoning_effort','model_verbosity','model_reasoning_summary','service_tier','approval_policy','sandbox_mode'
    $keepSec='desktop',"projects.'$Root'",'shell_environment_policy'
    $tpl=@(); $cur=''
    foreach ($line in ((& $read '.codex\config.toml') -split "`r?`n")) {
        if ($line -match '^\s*\[(.+)\]\s*$') { $cur=$matches[1]; if ($keepSec -contains $cur) { $tpl+=''; $tpl+=$line }; continue }
        if ($cur -eq '') { if ($line -match '^\s*([A-Za-z0-9_-]+)\s*=' -and $keepTop -contains $matches[1]) { $tpl+=$line } }
        elseif ($keepSec -contains $cur -and $line -match '\S') { $tpl+=$line }
    }
    $out['codex/config.toml']=& $hide ($tpl -join "`n")
    # write to a scratch copy first; the repo files change only when the scratch copy passes the checks
    $tmp=Join-Path $env:TEMP ('config-export-'+[guid]::NewGuid().ToString('N'))
    foreach ($f in $files) {
        $p=Join-Path $tmp $f; New-Item -ItemType Directory -Force (Split-Path $p) | Out-Null
        [IO.File]::WriteAllText($p, (($out[$f] -replace "`r`n","`n").Trim() + "`n"), (New-Object Text.UTF8Encoding $false))
    }
    $err=@(Test-ConfigFiles $tmp)
    if ($err.Count) { Remove-Item $tmp -Recurse -Force; $err | ForEach-Object { Write-Host "FAIL $_" }; exit 1 }
    foreach ($f in $files) { $d=Join-Path $repo $f; New-Item -ItemType Directory -Force (Split-Path $d) | Out-Null; Copy-Item (Join-Path $tmp $f) $d -Force }
    Remove-Item $tmp -Recurse -Force
}
$err=@(Test-ConfigFiles $repo)
if ($err.Count) { $err | ForEach-Object { Write-Host "FAIL $_" }; exit 1 }
Write-Host "ok $($files.Count) files"
